# Mode guide selector (called by chat_service before building the prompt)
# ══════════════════════════════════════════════════════════════════════════

def select_mode_guide(question: str) -> str:
    """Analyze user question to pick the appropriate mode guide.

    Returns the matching MODE_GUIDE_* string, defaulting to selling mode.
    """
    q = question.lower()
    if any(kw in q for kw in ("测评", "对比", "vs", "评测", "横评", "对比评测")):
        return MODE_GUIDE_REVIEW
    if any(kw in q for kw in ("开箱", "开箱测评", "开箱体验", "沉浸开箱", "第一视角")):
        return MODE_GUIDE_UNBOXING
    # Default: selling mode (带货)
    return MODE_GUIDE_SELLING
